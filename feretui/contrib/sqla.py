def is_auto_sequence_column(col: object) -> bool:
    """Determine if a column is generated by a DB sequence."""
    if not getattr(col, "primary_key", False):
        return False
    if getattr(col, "server_default", None) is not None:
        return True
    if getattr(col, "default", None) is not None:
        return True
    autoincrement = getattr(col, "autoincrement", False)
    if autoincrement is True:
        return True
    col_type = getattr(col, "type", None)
    return autoincrement == "auto" and isinstance(col_type, Integer)


def _column_to_field(
    col: object,
    pk_db_generated: bool | str = "auto",
) -> Field:
    """Map a SQLAlchemy column to a WTForms field."""
    validators = []
    is_auto_pk = (
        is_auto_sequence_column(col)
        if pk_db_generated == "auto"
        else bool(pk_db_generated)
    )
    is_manual_pk = bool(getattr(col, "primary_key", False) and not is_auto_pk)

    if not col.nullable and (
        is_manual_pk or (not col.primary_key and col.default is None)
    ):
        validators.append(DataRequired())

    label = col.name.replace("_", " ").title()

    if isinstance(col.type, Boolean):
        return BooleanField(label, validators=validators)
    if isinstance(col.type, Integer):
        return IntegerField(label, validators=validators)
    if isinstance(col.type, Numeric | Float):
        return FloatField(label, validators=validators)
    if isinstance(col.type, DateTime):
        return DateTimeField(label, validators=validators)
    if isinstance(col.type, Date):
        return DateField(label, validators=validators)
    if isinstance(col.type, Text):
        return TextAreaField(label, validators=validators)
    return StringField(label, validators=validators)


def model_to_form(
    model: type[Any],
    base_form: type[FeretUIForm] = FeretUIForm,
    exclude: set[str] | list[str] | None = None,
    pk_db_generated: bool | str = "auto",
) -> type[FeretUIForm]:
    """Generate a WTForms Form from a SQLAlchemy declarative model.

    :param model: SQLAlchemy declarative model class
    :type model: type
    :param base_form: Base form class
    :type base_form: type[:class:`feretui.form.FeretUIForm`]
    :param exclude: Set of column names to exclude
    :type exclude: set[str] | list[str] | None
    :param pk_db_generated: "auto", True (DB sequence), or False (manual input)
    :type pk_db_generated: bool | str
    :return: A generated FeretUIForm subclass
    :rtype: type[:class:`feretui.form.FeretUIForm`]
    """
    exclude_set = set(exclude or [])
    fields: dict[str, Any] = (
        {
            key: val
            for key, val in getattr(base_form, "__dict__", {}).items()
            if not key.startswith("_") and key != "Meta"
        }
        if base_form and base_form is not FeretUIForm
        else {}
    )

    mapper = inspect(model)

    if "pk" not in fields:
        fields["pk"] = HiddenField("ID")

    for col in mapper.columns:
        if col.name in exclude_set or col.name in fields:
            continue
        is_auto_pk = (
            is_auto_sequence_column(col)
            if pk_db_generated == "auto"
            else bool(pk_db_generated)
        )
        if col.primary_key and is_auto_pk:
            # Auto-generated DB sequence PK is omitted from visible form inputs
            continue
        fields[col.name] = _column_to_field(
            col, pk_db_generated=pk_db_generated
        )

    form_name = f"{model.__name__}AutoForm"
    if base_form is None or not issubclass(base_form, FeretUIForm):
        actual_bases = (FeretUIForm,)
    else:
        actual_bases = (base_form,)

    return type(form_name, actual_bases, fields)


class SQLACrudMixin:
    """CRUD operations mixin for SQLAlchemy declarative models."""

    @classmethod
    def get_by_id(cls: type[Any], db: object, pk: object) -> object:
        """Fetch a record by primary key."""
        col = getattr(cls, "id", None)
        if col is None:
            with suppress(Exception):
                mapper = inspect(cls)
                pks = list(mapper.primary_key)
                if pks:
                    col = pks[0]
        if col is not None and db is not None:
            inst = db.scalar(select(cls).where(col == pk))
            if not inst:
                with suppress(ValueError, TypeError):
                    inst = db.scalar(select(cls).where(col == int(pk)))
            return inst
        return None

    @classmethod
    def search_records(
        cls: type[Any],
        db: object,
        query: str = "",  # noqa: ARG003
        filters: dict[str, Any] | None = None,
        order_by: object = None,
        offset: int = 0,
        limit: int = 50,
    ) -> list[object]:
        """Search records with optional filters and pagination."""
        stmt = select(cls)
        if filters:
            for k, v in filters.items():
                if hasattr(cls, k):
                    col = getattr(cls, k)
                    if isinstance(v, list | tuple | set):
                        stmt = stmt.where(col.in_(v))
                    else:
                        stmt = stmt.where(col == v)
        if order_by is not None:
            stmt = stmt.order_by(order_by)
        stmt = stmt.offset(offset).limit(limit)
        return list(db.scalars(stmt).all())

    @classmethod
    def delete_records(cls: type[Any], db: object, pks: list[object]) -> None:
        """Delete records by primary keys respecting ORM cascades."""
        for pk in pks:
            inst = cls.get_by_id(db, pk)
            if inst:
                db.delete(inst)
        db.commit()


class SQLAlchemyResource(LCRUDResource, Resource):
    """Semi-automatic CRUD generation from SQLAlchemy Declarative models."""

    model: type[Any] | None = None
    session_factory: Any | None = None
    primary_key_attr: str | None = None
    pk_db_generated: bool | str = "auto"

    def get_db_session(
        self: "SQLAlchemyResource",
    ) -> AbstractContextManager[object]:
        """Return a SQLAlchemy session or context manager."""
        factory = self.session_factory
        res = factory() if callable(factory) else factory

        if hasattr(res, "__enter__"):
            return res

        @contextmanager
        def _cm() -> Iterator[object]:
            yield res

        return _cm()

    @classmethod
    def get_primary_key_attr(cls: type["SQLAlchemyResource"]) -> str:
        """Get the primary key attribute name from model or configuration."""
        if cls.primary_key_attr:
            return cls.primary_key_attr

        if cls.model:
            mapper = inspect(cls.model)
            pks = [c.name for c in mapper.primary_key]
            if pks:
                return pks[0]

        return "id"

    @classmethod
    def build(cls: type["SQLAlchemyResource"]) -> Resource:
        """Automatically create the Form if not provided."""
        if cls.model:
            existing_form = getattr(cls, "Form", None)
            has_custom_fields = bool(
                existing_form
                and hasattr(existing_form, "__dict__")
                and any(not k.startswith("_") for k in existing_form.__dict__),
            )
            if not has_custom_fields:
                cls.Form = model_to_form(
                    cls.model,
                    base_form=existing_form or FeretUIForm,
                    pk_db_generated=cls.pk_db_generated,
                )

        return super().build()

    def get_pk(self: "SQLAlchemyResource", instance: object) -> str:
        """Return string representation of the primary key of an instance."""
        pk_attr = self.get_primary_key_attr()
        return str(getattr(instance, pk_attr))

    def _build_search_clause(
        self: "SQLAlchemyResource",
        search_str: str,
    ) -> object:
        """Build OR-combined ILIKE clauses for full-text search."""
        search_cols = getattr(self, "search_fields", None)
        if not search_cols:
            search_cols = [
                c.name
                for c in inspect(self.model).columns
                if isinstance(c.type, String | Text)
            ]
        clauses = [
            getattr(self.model, c).ilike(f"%{search_str}%")
            for c in search_cols
            if hasattr(self.model, c)
        ]
        return or_(*clauses) if clauses else None

    def _inst_to_form(
        self: "SQLAlchemyResource",
        form_cls: type[FeretUIForm],
        inst: object,
    ) -> FeretUIForm:
        """Convert a model instance to a form instance."""
        data = {"pk": self.get_pk(inst)}
        for col_name in form_cls()._fields:
            if col_name != "pk" and hasattr(inst, col_name):
                data[col_name] = getattr(inst, col_name)
        return form_cls(data=data)

    def filtered_reads(
        self: "SQLAlchemyResource",
        form_cls: type[FeretUIForm],
        filters: list[tuple[str, list[str]]],
        offset: int,
        limit: int,
    ) -> dict[str, object]:
        """Fetch filtered records, count, and return dataset."""
        if not self.model:
            return {"total": 0, "forms": []}

        with self.get_db_session() as db:
            query = select(self.model)

            for field_name, values in filters:
                if field_name in ("search", "q") and values:
                    search_str = (
                        values[0] if isinstance(values, list) else str(values)
                    )
                    clause = (
                        self._build_search_clause(search_str)
                        if search_str
                        else None
                    )
                    if clause is not None:
                        query = query.where(clause)
                elif hasattr(self.model, field_name) and values:
                    col = getattr(self.model, field_name)
                    query = query.where(
                        col == values[0]
                        if len(values) == 1
                        else col.in_(values)
                    )

            count_query = select(func.count()).select_from(query.subquery())
            total = db.scalar(count_query) or 0

            query = query.offset(offset).limit(limit)
            instances = db.scalars(query).all()
            forms = [self._inst_to_form(form_cls, inst) for inst in instances]

            return {"total": total, "forms": forms}

    def create(self: "SQLAlchemyResource", form: FeretUIForm) -> str:
        """Create a new model instance from form data."""
        if not self.model:
            raise ResourceError("No model configured for SQLAlchemyResource")

        with self.get_db_session() as db:
            inst = self.model()
            pk_attr = self.get_primary_key_attr()
            for name, field in form._fields.items():
                if name == "pk":
                    if field.data is not None and not getattr(
                        inst,
                        pk_attr,
                        None,
                    ):
                        setattr(inst, pk_attr, field.data)
                elif hasattr(self.model, name) and field.data is not None:
                    is_auto_pk = (
                        is_auto_sequence_column(getattr(self.model, name))
                        if self.pk_db_generated == "auto"
                        else bool(self.pk_db_generated)
                    )
                    if name == pk_attr and field.data == "" and is_auto_pk:
                        continue
                    if isinstance(field, One2ManyField):
                        continue
                    val = field.data
                    col_attr = getattr(self.model, name)
                    if (
                        hasattr(col_attr, "type")
                        and isinstance(col_attr.type, Integer)
                        and isinstance(val, str)
                        and val.isdigit()
                    ):
                        val = int(val)
                    setattr(inst, name, val)

            db.add(inst)
            db.flush()
            self.save_relations(db, inst, form)
            db.commit()
            return self.get_pk(inst)

    def _populate_child_model(
        self: "SQLAlchemyResource",
        child_model: type,
        child_inst: object,
        row: dict[str, Any],
        child_pk_col: str,
    ) -> None:
        """Populate child model attributes from row dictionary."""
        for col_name, val in row.items():
            if col_name in ("id", "pk", child_pk_col):
                continue
            if hasattr(child_model, col_name):
                col_attr = getattr(child_model, col_name)
                if (
                    hasattr(col_attr, "type")
                    and isinstance(col_attr.type, Integer)
                    and isinstance(val, str)
                    and val.isdigit()
                ):
                    val = int(val)
                elif (
                    hasattr(col_attr, "type")
                    and isinstance(col_attr.type, Float)
                    and isinstance(val, str)
                ):
                    with suppress(ValueError):
                        val = float(val)
                setattr(child_inst, col_name, val)

    def _reconcile_one2many_relation(
        self: "SQLAlchemyResource",
        db: object,
        inst: object,
        rel: object,
        raw_rows: list[object],
    ) -> None:
        """Reconcile rows of a single one2many relation."""
        child_model = rel.mapper.class_
        child_mapper = inspect(child_model)
        child_pk_col = child_mapper.primary_key[0].name

        child_collection = getattr(inst, rel.key, None)
        if child_collection is None:
            return

        existing_by_pk = {}
        for child in list(child_collection):
            cpk = getattr(child, child_pk_col, None)
            if cpk is not None:
                existing_by_pk[str(cpk)] = child

        kept_pks = set()
        for row in raw_rows:
            if not isinstance(row, dict):
                continue
            row_pk = str(
                row.get(child_pk_col) or row.get("id") or row.get("pk") or ""
            )
            if row_pk and row_pk in existing_by_pk:
                child_inst = existing_by_pk[row_pk]
                kept_pks.add(row_pk)
                self._populate_child_model(
                    child_model,
                    child_inst,
                    row,
                    child_pk_col,
                )
            else:
                new_child = child_model()
                self._populate_child_model(
                    child_model,
                    new_child,
                    row,
                    child_pk_col,
                )
                child_collection.append(new_child)

        for old_pk, old_child in existing_by_pk.items():
            if old_pk not in kept_pks:
                child_collection.remove(old_child)
                db.delete(old_child)

    def save_relations(
        self: "SQLAlchemyResource",
        db: object,
        inst: object,
        form: FeretUIForm,
    ) -> None:
        """Persist or reconcile x2many relations during create and update."""
        mapper = inspect(self.model)
        for rel in mapper.relationships:
            rel_name = rel.key
            if rel_name not in form._fields:
                continue
            field = form._fields[rel_name]
            if not isinstance(field, One2ManyField):
                continue

            raw_rows = getattr(field, "data", None)
            if raw_rows is None:
                continue

            is_submitted = getattr(field, "is_submitted", False)
            has_dicts = raw_rows and all(isinstance(r, dict) for r in raw_rows)
            if not is_submitted and not has_dicts:
                continue

            self._reconcile_one2many_relation(db, inst, rel, raw_rows)

    def read(
        self: "SQLAlchemyResource",
        form_cls: type[FeretUIForm],
        pk: str,
    ) -> FeretUIForm:
        """Read a record by primary key."""
        if not self.model:
            raise ResourceError("No model configured for SQLAlchemyResource")

        with self.get_db_session() as db:
            pk_attr = self.get_primary_key_attr()
            col = getattr(self.model, pk_attr)
            inst = db.scalar(select(self.model).where(col == pk))
            if not inst:
                with suppress(ValueError, TypeError):
                    inst = db.scalar(select(self.model).where(col == int(pk)))

            if not inst:
                raise ResourceError(f"{self.model.__name__}[{pk}] not found")

            data = {"pk": str(pk)}
            for col_name in form_cls()._fields:
                if col_name != "pk" and hasattr(inst, col_name):
                    data[col_name] = getattr(inst, col_name)

            return form_cls(data=data)

    def update(
        self: "SQLAlchemyResource",
        forms: list[FeretUIForm],
    ) -> None:
        """Update model instances from form data."""
        if not self.model:
            raise ResourceError("No model configured for SQLAlchemyResource")

        with self.get_db_session() as db:
            pk_attr = self.get_primary_key_attr()
            col = getattr(self.model, pk_attr)
            for form in forms:
                pk = form.pk.data
                inst = db.scalar(select(self.model).where(col == pk))
                if not inst:
                    with suppress(ValueError, TypeError):
                        inst = db.scalar(
                            select(self.model).where(col == int(pk)),
                        )

                if inst:
                    for name, field in form._fields.items():
                        if (
                            name not in ("pk", pk_attr)
                            and hasattr(self.model, name)
                            and field.data is not None
                        ):
                            if isinstance(field, One2ManyField):
                                continue
                            val = field.data
                            col_attr = getattr(self.model, name)
                            if (
                                hasattr(col_attr, "type")
                                and isinstance(col_attr.type, Integer)
                                and isinstance(val, str)
                                and val.isdigit()
                            ):
                                val = int(val)
                            setattr(inst, name, val)

                    self.save_relations(db, inst, form)

            db.commit()

    def delete(self: "SQLAlchemyResource", pks: list[str]) -> None:
        """Delete model instances by primary keys respecting ORM cascades."""
        if not self.model:
            raise ResourceError("No model configured for SQLAlchemyResource")

        with self.get_db_session() as db:
            pk_attr = self.get_primary_key_attr()
            col = getattr(self.model, pk_attr)
            cast_pks: list[Any] = []
            for pk in pks:
                cast_pks.append(pk)
                with suppress(ValueError, TypeError):
                    cast_pks.append(int(pk))

            instances = db.scalars(
                select(self.model).where(col.in_(cast_pks))
            ).all()
            for inst in instances:
                db.delete(inst)
            db.commit()

    def move_card(
        self: "SQLAlchemyResource",
        pk: str,
        stage: str,
        index: int | None = None,  # noqa: ARG002
    ) -> None:
        """Update card stage when dragged in Kanban view."""
        if not self.model:
            raise ResourceError("No model configured for SQLAlchemyResource")

        if isinstance(pk, list | tuple):
            pk = pk[0] if pk else None
        if isinstance(stage, list | tuple):
            stage = stage[0] if stage else None

        with self.get_db_session() as db:
            pk_attr = self.get_primary_key_attr()
            col = getattr(self.model, pk_attr)
            inst = db.scalar(select(self.model).where(col == pk))
            if not inst:
                with suppress(ValueError, TypeError):
                    inst = db.scalar(select(self.model).where(col == int(pk)))

            if inst:
                col_field = "status"
                if hasattr(self, "views") and "kanban" in self.views:
                    col_field = getattr(
                        self.views["kanban"],
                        "column_field",
                        "status",
                    )
                if hasattr(inst, col_field):
                    setattr(inst, col_field, stage)
                elif hasattr(inst, "stage"):
                    inst.stage = stage

                db.commit()
